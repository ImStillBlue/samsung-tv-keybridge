            foreach (string invalid in new[] { "HEARTBEAT\t0", "HEARTBEAT\t2", "HEARTBEAT\t01", "HEARTBEAT\t+1", "HEARTBEAT\t-1", "READY", "HEARTBEAT\t1\tx" })
